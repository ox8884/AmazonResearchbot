import {browserSigningFixture} from './support/browser-signing-fixture.mjs';
import {publishBrowserSigningIdentity} from '../apps/worker/src/browser-signing-key.ts';
import assert from 'node:assert/strict';
import {openAcceptance,otp} from './support/acceptance.mjs';
const test=await openAcceptance({databaseKey:'bridge-pairing-acceptance'});
const listenOrigin=await test.app.listen({port:0,host:'127.0.0.1'});
const machine=async(url,body,token)=>{
 const response=await fetch(listenOrigin+url,{method:body===undefined?'GET':'POST',headers:{...(token?{authorization:'Bearer '+token}:{}),origin:'http://localhost:5173',...(body===undefined?{}:{'content-type':'application/json'})},...(body===undefined?{}:{body:JSON.stringify(body)})});
 return {status:response.status,body:await response.json(),cacheControl:response.headers.get('cache-control')};
};
try {
 const ownerId=(await test.call('/api/session')).body.user.id;
 const signing=await publishBrowserSigningIdentity(test.pool,browserSigningFixture().privateKey);
 assert.equal((await test.call('/api/bridge/pairings',{}, {origin:'https://foreign.invalid'})).status,403);
 assert.equal((await machine('/api/bridge/pairings',{})).status,401);
 const issued=await test.call('/api/bridge/pairings',{});
 assert.equal(issued.status,201);
 assert.equal((await test.call('/api/bridge/pairings/'+issued.body.id)).body.state,'pending');
 assert.match(issued.body.pairingCode,/^fbp_[a-f0-9]{64}$/);
 assert.ok(Date.parse(issued.body.expiresAt)-Date.now()<=300_000);
 const redeem=()=>machine('/api/bridge/pair',{pairingCode:issued.body.pairingCode,name:'Synthetic browser device'});
 const redeemed=await Promise.all([redeem(),redeem()]);
 assert.deepEqual(redeemed.map(r=>r.status).sort(),[201,401]);
 const accepted=redeemed.find(r=>r.status===201);assert.equal(accepted.cacheControl,'no-store');
 const device=accepted.body;
 assert.equal((await test.call('/api/bridge/pairings/'+issued.body.id)).body.state,'consumed');
 assert.match(device.credential,/^fbd_[a-f0-9]{64}$/);
 assert.equal((await machine('/api/bridge/device',undefined,device.credential)).body.browserAvailable,false);
 assert.equal((await machine('/api/candidates',undefined,device.credential)).status,401);
 assert.equal((await machine('/api/bridge/pair',{pairingCode:issued.body.pairingCode,name:'Replay'})).status,401);
 let list=await test.call('/api/bridge/devices');
 assert.equal(list.status,200);assert.ok(list.body.devices.some(row=>row.id===device.id));
 assert.equal(JSON.stringify(list.body).includes(device.credential),false);
 const deviceState=async()=> (await machine('/api/bridge/device',undefined,device.credential)).body;
 assert.equal((await deviceState()).connectionState,'unreported');
 assert.equal((await machine('/api/bridge/capabilities',{connected:true,supportedTasks:['supplier_search'],keyFingerprint:signing.fingerprint},device.credential)).status,200);
 assert.equal((await deviceState()).browserAvailable,true);
 assert.equal((await deviceState()).connectionState,'ready');
 assert.equal((await test.call('/api/bridge/devices')).body.devices.find(row=>row.id===device.id).connectionState,'ready');
 await test.pool.query("UPDATE bridge_devices SET reported_at=now()-interval '91 seconds' WHERE id=$1",[device.id]);
 assert.equal((await deviceState()).connectionState,'stale');
 assert.equal((await deviceState()).browserAvailable,false);
 await machine('/api/bridge/capabilities',{connected:false,supportedTasks:[],keyFingerprint:signing.fingerprint},device.credential);
 assert.equal((await deviceState()).connectionState,'offline');
 await machine('/api/bridge/capabilities',{connected:true,supportedTasks:[],keyFingerprint:signing.fingerprint},device.credential);
 assert.equal((await deviceState()).connectionState,'unsupported');

 const stored=await test.pool.query('SELECT to_jsonb(p) AS pairing,to_jsonb(d) AS device FROM bridge_pairings p JOIN bridge_devices d ON d.pairing_id=p.id WHERE d.id=$1',[device.id]);
 assert.equal(JSON.stringify(stored.rows).includes(issued.body.pairingCode),false);
 assert.equal(JSON.stringify(stored.rows).includes(device.credential),false);
 const replaced=(await test.call('/api/bridge/pairings',{})).body;
 await test.call('/api/bridge/pairings',{});
 assert.equal((await machine('/api/bridge/pair',{pairingCode:replaced.pairingCode,name:'Replaced'})).status,401);
 assert.equal((await test.call('/api/bridge/pairings/'+replaced.id)).body.state,'cancelled');
 const otherPassword='Synthetic-Other-'+test.runId;
 assert.equal((await test.call('/api/auth/sign-up/email',{email:'other-'+test.runId+'@fixture.invalid',password:otherPassword,name:'Other fixture'})).status,200);
 assert.equal((await test.call('/api/bridge/pairings',{})).status,403);
 const enrollment=(await test.call('/api/auth/two-factor/enable',{password:otherPassword,method:'totp'})).body;
 assert.equal((await test.call('/api/auth/two-factor/verify-totp',{code:otp(new URL(enrollment.totpURI).searchParams.get('secret'))})).status,200);
 assert.deepEqual((await test.call('/api/bridge/devices')).body.devices,[]);
 assert.equal((await test.call('/api/bridge/pairings/'+issued.body.id)).status,404);
 assert.equal((await test.call('/api/bridge/devices/'+device.id+'/revoke',{})).status,404);
 await test.call('/api/auth/sign-out',{});
 assert.equal((await test.call('/api/auth/sign-in/email',{email:test.authFixture.email,password:test.authFixture.password})).body.twoFactorRedirect,true);
 assert.equal((await test.call('/api/auth/two-factor/verify-totp',{code:otp(test.authFixture.totpSecret)})).status,200);
 const expired=(await test.call('/api/bridge/pairings',{})).body;
 await test.pool.query("UPDATE bridge_pairings SET expires_at=now()-interval '1 second' WHERE id=$1",[expired.id]);
 assert.equal((await machine('/api/bridge/pair',{pairingCode:expired.pairingCode,name:'Expired'})).status,401);
 assert.equal((await test.call('/api/bridge/pairings/'+expired.id)).body.state,'expired');
 assert.equal((await test.call('/api/bridge/devices/'+device.id+'/revoke',{})).status,200);
 assert.equal((await machine('/api/bridge/device',undefined,device.credential)).status,401);
 assert.equal((await test.call('/api/bridge/devices')).body.devices.find(row=>row.id===device.id).connectionState,'revoked');
 const revokedAudit=await test.pool.query("SELECT action,target FROM audit_events WHERE action='bridge_device_revoked' AND target=$1",[device.id]);
 assert.equal(revokedAudit.rowCount,1);
 assert.equal((await test.call('/api/bridge/devices/'+device.id+'/revoke',{})).status,200);
 assert.equal((await test.pool.query("SELECT id FROM audit_events WHERE action='bridge_device_revoked' AND target=$1",[device.id])).rowCount,1);
 const resetPairing=(await test.call('/api/bridge/pairings',{})).body;
 const resetDevice=(await machine('/api/bridge/pair',{pairingCode:resetPairing.pairingCode,name:'Reset fixture'})).body;
 await test.pool.query('UPDATE "user" SET two_factor_enabled=false WHERE id=$1',[ownerId]);
 try{assert.equal((await machine('/api/bridge/device',undefined,resetDevice.credential)).status,401);}
 finally{await test.pool.query('UPDATE "user" SET two_factor_enabled=true WHERE id=$1',[ownerId]);}

 assert.equal((await machine('/api/bridge/device',undefined,resetDevice.credential)).status,401,'Re-enabling 2FA must not revive the old machine credential');
 assert.equal((await test.call('/api/auth/sign-in/email',{email:test.authFixture.email,password:test.authFixture.password})).body.twoFactorRedirect,true);
 assert.equal((await test.call('/api/auth/two-factor/verify-totp',{code:otp(test.authFixture.totpSecret)})).status,200);
 const pending=(await test.call('/api/bridge/pairings',{})).body;
 await test.call('/api/auth/sign-out',{});
 assert.equal((await machine('/api/bridge/pair',{pairingCode:pending.pairingCode,name:'After logout'})).status,401);
 console.log(JSON.stringify({scenario:'bridge-pairing',result:'PASS',singleUse:true,expiry:true,revocation:true,ownerIsolation:true,twoFactorRequired:true,credentialResetRevokesDevice:true,businessAccess:false,browserAvailable:false,externalCalls:0,loopbackHttp:true}));
}finally{await test.close();}
